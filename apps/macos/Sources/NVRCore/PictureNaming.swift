import Foundation

/// The image formats a saved picture can have (docs/CAPTURE.md "Save
/// picture"): PNG, or JPEG at quality 0.9.
public enum PictureFormat: String, CaseIterable, Sendable {
    case png
    case jpeg

    /// The file extension: `png` or `jpg`.
    public var fileExtension: String { self == .png ? "png" : "jpg" }

    /// The quality JPEG pictures are written at.
    public static let jpegQuality = 0.9

    /// The title in Settings and the save panel.
    public var title: String { self == .png ? "PNG" : "JPEG" }

    /// The format a file name's extension says (`.jpg`, `.jpeg`, `.png`).
    public init?(extension ext: String) {
        switch ext.lowercased() {
        case "png": self = .png
        case "jpg", "jpeg": self = .jpeg
        default: return nil
        }
    }
}

/// The names of saved pictures (docs/CAPTURE.md "Save picture", the
/// still-image rule of FFI-RECORDINGS.md section 7a):
/// `YYYY-MM-DD HH.MM.SS.mmm <camera>.png`, the camera name sanitized, the
/// whole stem at most 120 characters, `Camera A` with share-safe names, and
/// ` (2)`, ` (3)` before the extension when the name is taken. Pure; the
/// vectors in `fixtures/synthetic/capture-names.json` are generated by the
/// Rust rules (`capture::naming`) and read here and by the Windows app, so
/// the three agree. Characters are Unicode scalars, as Rust's `char`.
public enum PictureNaming {
    /// The longest sanitized name, in characters.
    public static let maxNameChars = 120
    /// Names tried before giving up (the core's `MAX_NAME_TRIES`).
    public static let maxTries = 1000
    /// The neutral name share-safe names use.
    public static let shareSafeLabel = "Camera A"

    /// Replaces characters that are not allowed in file names on macOS,
    /// Windows, or Linux, collapses runs of spaces, trims what Windows
    /// rejects at the ends, and caps the length; `_` when nothing is left.
    public static func sanitize(_ name: String) -> String {
        var scalars: [Unicode.Scalar] = []
        for c in name.unicodeScalars {
            var c = c
            switch c {
            case "/", "\\", ":", "*", "?", "\"", "<", ">", "|": c = "-"
            default: if c.properties.generalCategory == .control { c = " " }
            }
            if c == " ", scalars.last == " " { continue }
            scalars.append(c)
        }
        while let f = scalars.first, f.properties.isWhitespace { scalars.removeFirst() }
        while let l = scalars.last, l.properties.isWhitespace { scalars.removeLast() }
        scalars = Array(scalars.prefix(maxNameChars))
        while let l = scalars.last, l == "." || l == " " { scalars.removeLast() }
        if scalars.isEmpty { return "_" }
        var s = String.UnicodeScalarView()
        s.append(contentsOf: scalars)
        return String(s)
    }

    /// The camera's name as it appears in a file name: its own, or
    /// `Camera A` when share-safe.
    public static func cameraLabel(_ camera: String, shareSafe: Bool) -> String {
        shareSafe ? shareSafeLabel : camera
    }

    /// Milliseconds since the Unix epoch of the clock on the wall at `date`
    /// in `timeZone` (the "local naive" time the stamp is made from).
    public static func localMillis(_ date: Date, in timeZone: TimeZone = .current) -> Int64 {
        let utc = Int64((date.timeIntervalSince1970 * 1000).rounded(.down))
        return utc + Int64(timeZone.secondsFromGMT(for: date)) * 1000
    }

    /// `2026-10-11 17.02.03.250` from local naive milliseconds.
    public static func stamp(localMillis ms: Int64) -> String {
        let secs = floorDiv(ms, 1000)
        let milli = ms - secs * 1000
        let days = floorDiv(secs, 86400)
        let rest = secs - days * 86400
        // Civil date from days since 1970-01-01 (proleptic Gregorian).
        let z = days + 719_468
        let era = floorDiv(z, 146_097)
        let doe = z - era * 146_097
        let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146_096) / 365
        let doy = doe - (365 * yoe + yoe / 4 - yoe / 100)
        let mp = (5 * doy + 2) / 153
        let day = doy - (153 * mp + 2) / 5 + 1
        let month = mp < 10 ? mp + 3 : mp - 9
        let year = yoe + era * 400 + (month <= 2 ? 1 : 0)
        func two(_ v: Int64) -> String { v < 10 ? "0\(v)" : "\(v)" }
        let ms3 = milli < 10 ? "00\(milli)" : milli < 100 ? "0\(milli)" : "\(milli)"
        let y = year < 1000 ? String(repeating: "0", count: 4 - String(year).count) + "\(year)" : "\(year)"
        return "\(y)-\(two(month))-\(two(day)) \(two(rest / 3600)).\(two(rest % 3600 / 60)).\(two(rest % 60)).\(ms3)"
    }

    /// The first stem name, `…<camera>.png`, then `… (2).png` and so on,
    /// for which `taken` (asked with the file name) is false; nil if every
    /// try is taken.
    public static func fileName(
        localMillis ms: Int64, camera: String, shareSafe: Bool, format: PictureFormat,
        taken: (String) -> Bool
    ) -> String? {
        let stem = sanitize("\(stamp(localMillis: ms)) \(cameraLabel(camera, shareSafe: shareSafe))")
        let ext = format.fileExtension
        let first = "\(stem).\(ext)"
        if !taken(first) { return first }
        for n in 2...maxTries {
            let candidate = "\(stem) (\(n)).\(ext)"
            if !taken(candidate) { return candidate }
        }
        return nil
    }

    private static func floorDiv(_ a: Int64, _ b: Int64) -> Int64 {
        let q = a / b
        return (a % b != 0 && (a < 0) != (b < 0)) ? q - 1 : q
    }
}
