//! The shared picture-name vectors, `fixtures/synthetic/capture-names.json`
//! (docs/CAPTURE.md, "Save picture"). The Rust rules generate them; the macOS
//! tests (`PictureNamingTests`) and the Windows tests read the same file, so
//! the implementations agree. `NVRVIEW_UPDATE_VECTORS=1 cargo test -p capture
//! --test name_vectors` rewrites the file; otherwise the test fails when the
//! file differs from what the rules produce.

use capture::naming::{StillFormat, camera_label, picture_file_name};
use recordings::naming::sanitize;
use serde_json::{Value, json};
use std::collections::HashSet;
use std::path::PathBuf;

fn file() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../fixtures/synthetic/capture-names.json")
}

/// One picture case: local naive milliseconds, camera, share-safe, format,
/// and the names already taken in the folder.
type Case = (i64, String, bool, StillFormat, Vec<String>);

fn vectors() -> Value {
    let sanitize_inputs = [
        "Camera 1",
        "a<b>c:d\"e|f?g*h\\i/j",
        "  name.  ",
        "tab\there\nnew",
        "...",
        "",
        "two  spaces   inside",
        "trailing dot.",
        "Garden \u{e9}t\u{e9} \u{1f333}",
    ];
    let long = "x".repeat(500);
    let mut sanitize_cases: Vec<Value> = sanitize_inputs
        .iter()
        .map(|s| json!({ "input": s, "expected": sanitize(s) }))
        .collect();
    sanitize_cases.push(json!({ "input": long, "expected": sanitize(&long) }));

    let a = 1_791_738_123_250_i64;
    let taken_a = "2026-10-11 17.02.03.250 Camera 1.png".to_string();
    let cases: Vec<Case> = vec![
        (a, "Camera 1".into(), false, StillFormat::Png, vec![]),
        (a, "Camera 1".into(), false, StillFormat::Jpeg, vec![]),
        (
            a,
            "Front/Door: <main>".into(),
            false,
            StillFormat::Png,
            vec![],
        ),
        (a, "Camera 1".into(), true, StillFormat::Png, vec![]),
        (
            a,
            "Camera 1".into(),
            false,
            StillFormat::Png,
            vec![taken_a.clone()],
        ),
        (
            a,
            "Camera 1".into(),
            false,
            StillFormat::Png,
            vec![
                taken_a.clone(),
                "2026-10-11 17.02.03.250 Camera 1 (2).png".into(),
            ],
        ),
        (
            a,
            "Camera 1".into(),
            false,
            StillFormat::Jpeg,
            vec![taken_a],
        ),
        (
            a,
            "Camera 1".into(),
            true,
            StillFormat::Png,
            vec!["2026-10-11 17.02.03.250 Camera A.png".into()],
        ),
        (0, "Epoch".into(), false, StillFormat::Png, vec![]),
        (1_000, "Edge".into(), false, StillFormat::Png, vec![]),
        (a + 1, "Millis".into(), false, StillFormat::Jpeg, vec![]),
        (a, "n".repeat(300), false, StillFormat::Png, vec![]),
        (a, "Trailing.".into(), false, StillFormat::Png, vec![]),
        (a, "".into(), false, StillFormat::Png, vec![]),
    ];
    let picture_cases: Vec<Value> = cases
        .iter()
        .map(|(ms, camera, share_safe, format, taken)| {
            let set: HashSet<&str> = taken.iter().map(String::as_str).collect();
            let expected =
                picture_file_name(*ms, camera, *share_safe, *format, |n| set.contains(n))
                    .expect("a free name");
            json!({
                "ms": ms,
                "camera": camera,
                "shareSafe": share_safe,
                "format": match format { StillFormat::Png => "png", StillFormat::Jpeg => "jpeg" },
                "taken": taken,
                "expected": expected,
            })
        })
        .collect();

    json!({
        "comment": "Generated by crates/capture/tests/name_vectors.rs; do not edit by hand.",
        "maxNameChars": recordings::naming::MAX_NAME_CHARS,
        "shareSafeLabel": camera_label("anything", true),
        "sanitize": sanitize_cases,
        "picture": picture_cases,
    })
}

#[test]
fn the_shared_vector_file_matches_the_rules() {
    let text = serde_json::to_string_pretty(&vectors()).unwrap() + "\n";
    if std::env::var_os("NVRVIEW_UPDATE_VECTORS").is_some() {
        std::fs::write(file(), &text).unwrap();
        return;
    }
    let on_disk = std::fs::read_to_string(file()).expect("fixtures/synthetic/capture-names.json");
    assert_eq!(
        on_disk, text,
        "capture-names.json is stale; rerun with NVRVIEW_UPDATE_VECTORS=1"
    );
}
